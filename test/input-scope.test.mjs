for (const [name, parse, u, a, context, badContext] of [
  ['Claude', claudePairs, cu, ca, cwd => ({ type: 'system', cwd }), { type: 'system', cwd: '/synthetic/b', source: 'automation' }],
  ['Codex', codexPairs, xu, xa, cwd => xm({ cwd, source: 'cli' }), { type: 'turn_context', payload: { cwd: '/synthetic/b', source: 'automation' } }],
]) {
  test(`${name}: malformed and oversized rows clear pending answers and stale cwd`, () => {
    const oversized = name === 'Claude'
      ? JSON.stringify({ ...badContext, developer_instructions: 'x'.repeat(MAX_LINE + 1) })
      : JSON.stringify({ ...badContext, payload: { ...badContext.payload, developer_instructions: 'x'.repeat(MAX_LINE + 1) } })
    const malformed = JSON.stringify(badContext).slice(0, -1) + ',BROKEN'
    for (const unreadable of [oversized, malformed, 'null', '[]']) {
      // An untagged continuation cannot attach to an earlier human request.
      const oldExchange = fixtureWithUnreadable([context('/synthetic/a'), u('Old request'), a('Old answer')], unreadable, [a('Untagged continuation'), u('Next human')])
      assert.equal(parse(oldExchange).length, 0)
      // A fresh human exchange is report-compatible, but never scoped using stale A.
      const fresh = fixtureWithUnreadable([context('/synthetic/a')], unreadable, [u('New human request'), a('New answer'), u('Correction')])
      const pairs = parse(fresh)
      assert.equal(pairs.length, 1)
      assert.equal(Object.hasOwn(pairs[0], 'project'), false)
      assert.equal(pairs[0].origin, 'history-user')
      // Only a later readable authoritative cwd can restore directory scope.
      const restored = fixtureWithUnreadable([context('/synthetic/a')], unreadable, [context('/synthetic/c'), u('New request'), a('New answer'), u('Correction')])
      assert.equal(parse(restored)[0].project, projectKey('/synthetic/c'))
    }
  })
}

