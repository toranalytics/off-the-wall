test('scope accepts only absolute cwd and emits SHA256 keys, never raw paths', () => {
  for (const cwd of [undefined, null, 0, false, '0', '', ' ', '.', 'relative/project', 'C:relative', '\\relative', {}, '/bad\0path']) assert.equal(projectKey(cwd), undefined)
  const key = projectKey('/synthetic/project')
  assert.equal(isProjectKey(key), true)
  assert.match(key, /^cwd:[0-9a-f]{64}$/)
  assert.equal(key.includes('synthetic'), false)
  for (const value of ['/synthetic/project', 'cwd:abc', `cwd:${'A'.repeat(64)}`, {}, null]) assert.equal(isProjectKey(value), false)
  assert.equal(projectKey('/synthetic/a/../project/'), key)
  assert.notEqual(projectKey('/synthetic/Project'), key)
  assert.notEqual(projectKey('//Synthetic/Project'), projectKey('//synthetic/project'))
  assert.equal(projectKey('//synthetic/project'), key)
  assert.notEqual(projectKey('/synthetic/project/subdir'), key)
  assert.notEqual(projectKey('/synthetic/project\\'), key)
})

